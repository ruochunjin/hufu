"""Benchmark dataset loaders for HuFu consistency evaluation.

Unified access to the contradiction/NLI datasets used by the HyperMatch and
DocChecker papers.  Loaders yield normalized ``NLIExample`` records; raw data
lives under ``benchmarks/data/`` (small datasets may be committed — the lab
approved releasing evaluation data with the repo — while large ones are
fetched on demand from Hugging Face, honoring ``HF_ENDPOINT`` for mirrors).

Datasets (2026-10-03 survey):
- ContraDoc: GitHub ddhruvkr/CONTRADOC, ``ContraDoc.json`` at repo root
  (449 contradictory + 442 clean long documents, Apache-2.0).
- ContractNLI: HF ``kiddothe2b/contract-nli`` (LexGLUE distribution).
- DocNLI: HF ``tasksource/doc-nli``.
- ConTRoL: HF ``tasksource/ConTRoL-nli``.
- ECON: GitHub HKUST-KnowComp/EvidenceConflict — data is LLM-generated by
  their pipeline, not shipped; ingestion deferred (needs generation).
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator, Literal

Label = Literal["contradiction", "entailment", "neutral"]

DATA_DIR = Path(__file__).parent / "data"

_CONTRADOC_URL = (
    "https://raw.githubusercontent.com/ddhruvkr/CONTRADOC/main/ContraDoc.json"
)


@dataclass(frozen=True)
class NLIExample:
    """One normalized evaluation example."""

    source: str
    example_id: str
    premise: str
    hypothesis: str
    label: Label
    meta: dict = field(default_factory=dict)


def ensure_contradoc(path: Path | None = None) -> Path:
    """Return the local ContraDoc.json path, downloading it if missing."""

    target = path or (DATA_DIR / "ContraDoc.json")
    if target.exists():
        return target
    import urllib.request

    target.parent.mkdir(parents=True, exist_ok=True)
    urllib.request.urlretrieve(_CONTRADOC_URL, target)  # noqa: S310 - pinned URL
    return target


def load_contradoc(path: Path | None = None) -> Iterator[NLIExample]:
    """Yield ContraDoc documents as document-level contradiction examples.

    Positive (self-contradictory) documents carry the injected ``evidence``
    sentence plus optional ``ref sentences`` it contradicts; the pair
    (ref sentences, evidence) is a ready-made query–document contradiction
    case for ``check_pair``.
    """

    data = json.loads(ensure_contradoc(path).read_text(encoding="utf-8"))
    for doc_id, doc in data.get("pos", {}).items():
        yield NLIExample(
            source="contradoc",
            example_id=doc_id,
            premise=doc["text"],
            hypothesis=doc.get("evidence", ""),
            label="contradiction",
            meta={
                "doc_type": doc.get("doc_type"),
                "contra_type": doc.get("contra_type"),
                "scope": doc.get("scope"),
                "ref_sentences": doc.get("ref sentences", []),
            },
        )
    for doc_id, doc in data.get("neg", {}).items():
        yield NLIExample(
            source="contradoc",
            example_id=doc_id,
            premise=doc["text"],
            hypothesis="",
            label="entailment",
            meta={"doc_type": doc.get("doc_type")},
        )


_HF_DATASETS: dict[str, dict] = {
    "contract_nli": {
        "hf_id": "kiddothe2b/contract-nli",
        "config": "contractnli_a",
        "premise_key": "premise",
        "hypothesis_key": "hypothesis",
        "label_key": "label",
        # LexGLUE labels: 0=entailment, 1=neutral, 2=contradiction
        "label_map": {0: "entailment", 1: "neutral", 2: "contradiction"},
    },
    "docnli": {
        "hf_id": "tasksource/doc-nli",
        "premise_key": "premise",
        "hypothesis_key": "hypothesis",
        "label_key": "label",
        "label_map": {0: "entailment", 1: "not_entailment"},
    },
    "control": {
        "hf_id": "tasksource/ConTRoL-nli",
        "premise_key": "premise",
        "hypothesis_key": "hypothesis",
        "label_key": "label",
        "label_map": {0: "entailment", 1: "not_entailment"},
    },
}


def _load_rows(hf_id: str, config: str | None, split: str):
    """Load a dataset split, falling back to the parquet API for script datasets.

    ``kiddothe2b/contract-nli`` still ships a legacy loader script, which
    ``datasets>=3`` rejects; every such dataset also has an automatic parquet
    conversion served from the hub API.  URLs are rewritten onto
    ``HF_ENDPOINT`` so mirrors keep working.
    """

    from datasets import load_dataset

    try:
        return load_dataset(hf_id, config, split=split) if config else load_dataset(hf_id, split=split)
    except RuntimeError as exc:
        if "Dataset scripts are no longer supported" not in str(exc):
            raise
    import json
    import urllib.request

    endpoint = os.environ.get("HF_ENDPOINT", "https://huggingface.co").rstrip("/")
    api_url = f"{endpoint}/api/datasets/{hf_id}/parquet"
    request = urllib.request.Request(
        api_url, headers={"User-Agent": "hufu-benchmarks/0.4 (datasets)"}
    )
    with urllib.request.urlopen(request) as response:  # noqa: S310 - hub API
        catalog = json.load(response)
    configs = catalog if config is None else {config: catalog[config]}
    urls = []
    for config_name, splits in configs.items():
        if split in splits:
            urls.extend(splits[split])
    if not urls:
        raise ValueError(f"no parquet files for {hf_id} config={config} split={split}")
    urls = [
        url.replace("https://huggingface.co", endpoint, 1) if url.startswith("https://huggingface.co") else url
        for url in urls
    ]
    # The parquet-API URLs redirect to the real files; the ``datasets`` hub
    # filesystem cannot resolve them through mirrors, so download to a local
    # cache (which also makes reruns fully offline).
    cache_dir = DATA_DIR / "cache" / hf_id.replace("/", "--") / (config or "default") / split
    cache_dir.mkdir(parents=True, exist_ok=True)
    local_files = []
    for url in urls:
        target = cache_dir / url.rsplit("/", 1)[-1]
        if not target.exists():
            request = urllib.request.Request(
                url, headers={"User-Agent": "hufu-benchmarks/0.4 (datasets)"}
            )
            with urllib.request.urlopen(request) as response, open(target, "wb") as out:  # noqa: S310
                out.write(response.read())
        local_files.append(str(target))
    return load_dataset("parquet", data_files={split: local_files}, split=split)


def load_hf_nli(
    name: str,
    *,
    split: str = "test",
    limit: int | None = None,
) -> Iterator[NLIExample]:
    """Yield normalized examples from a Hugging Face NLI dataset.

    Requires the ``datasets`` package.  Honors ``HF_ENDPOINT`` (e.g.
    ``https://hf-mirror.com``) and ``HF_HUB_OFFLINE=1`` for cached runs.
    """

    if name not in _HF_DATASETS:
        raise ValueError(f"unknown dataset {name!r}; expected one of {sorted(_HF_DATASETS)}")
    spec = _HF_DATASETS[name]
    rows = _load_rows(spec["hf_id"], spec.get("config"), split)
    label_map = spec["label_map"]
    for index, row in enumerate(rows):
        if limit is not None and index >= limit:
            break
        raw_label = row[spec["label_key"]]
        mapped = label_map.get(raw_label, "neutral")
        if mapped == "not_entailment":
            mapped = "neutral"
        yield NLIExample(
            source=name,
            example_id=str(row.get("id", index)),
            premise=row[spec["premise_key"]],
            hypothesis=row[spec["hypothesis_key"]],
            label=mapped,  # type: ignore[arg-type]
            meta={"raw_label": raw_label},
        )


